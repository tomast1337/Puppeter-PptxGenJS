import { copyFile, mkdir, readdir, unlink, writeFile } from "node:fs/promises";
import { join } from "node:path";
import type { NormalizedPresentation } from "@pdflapas/model";

export interface GalleryPage {
    page: string;
    title: string;
    referenceName: string;
    actualName: string;
}

/**
 * One title per printed page, derived from the deck so it cannot fall out of step with the fixture (#225): the first
 * line of the slide's first text box, or, for a page without text (a table continuation, a component slide), the
 * kinds of object it holds. Hidden slides print no page, so they have no title.
 */
export function galleryPageTitles(model: NormalizedPresentation): string[] {
    return model.slides
        .filter(slide => !slide.hidden)
        .map(slide => {
            const text = slide.objects.find(object => object.kind === "text");
            const title =
                text?.kind === "text"
                    ? text.text.paragraphs[0]?.runs
                          .map(run => run.text)
                          .join("")
                          .trim()
                    : undefined;

            return title || `Untitled: ${[...new Set(slide.objects.map(object => object.kind))].join(", ")}`;
        });
}

function image(page: string, kind: "reference" | "actual", description: string): string {
    return `<img src="assets/${page}-${kind}.png" width="260" alt="Page ${page} ${description}">`;
}

function galleryMarkdown(pages: GalleryPage[], scores: number[], threshold: number): string {
    if (scores.length !== pages.length) {
        throw new Error(`Gallery metadata mismatch: pages=${pages.length}, scores=${scores.length}`);
    }

    const rows = pages.map((page, index) => `| **${page.page} — ${page.title}** (\`${scores[index]?.toFixed(4)}\`) | ${image(page.page, "reference", "reference")} | ${image(page.page, "actual", "PuppeteerGen output")} |`).join("\n");

    return `<!-- Generated by: bun run test:visual:gallery -->
# Visual parity gallery

This gallery compares the same fixture rendered by the pinned PptxGenJS version
and by PuppeteerGen. The PptxGenJS presentation is converted to PDF with
LibreOffice; both PDFs are rasterized at 96 DPI before comparison.

- **Reference:** PptxGenJS → PPTX → LibreOffice PDF
- **Actual:** PuppeteerGen → Puppeteer PDF
- **Score:** whole-slide normalized RMSE; the acceptance limit is \`${threshold.toFixed(2)}\`

The visual test is the source of truth. Regenerate this folder after intentional
rendering changes with:

\`\`\`bash
bun run test:visual:gallery
\`\`\`

The command publishes only the ${pages.length} full-page comparison pairs. Feature-level
crops remain transient test artifacts.

| Page, feature, and RMSE | Reference | PuppeteerGen |
| --- | --- | --- |
${rows}
`;
}

export async function writeVisualGallery(artifacts: string, pages: GalleryPage[], scores: number[], threshold: number, outputDirectory: string): Promise<void> {
    const assets = join(outputDirectory, "assets");

    await mkdir(assets, { recursive: true });
    const generatedName = /^\d+-(?:reference|actual|diff)\.png$/;

    await Promise.all((await readdir(assets)).filter(name => generatedName.test(name)).map(name => unlink(join(assets, name))));
    await Promise.all(pages.flatMap(page => [copyFile(join(artifacts, page.referenceName), join(assets, page.referenceName)), copyFile(join(artifacts, page.actualName), join(assets, page.actualName))]));
    await writeFile(join(outputDirectory, "README.md"), galleryMarkdown(pages, scores, threshold));
}
